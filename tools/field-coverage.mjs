#!/usr/bin/env node
// XSD field coverage report (roadmap B-19).
//
//   node tools/field-coverage.mjs
//
// Extracts every element/attribute name the FMI 2 and FMI 3 XSD schemas
// declare, then checks which of them the typed model in src/schema actually
// parses (a name counts as covered when it appears as a string literal in
// the parser or model sources). The report lands in
// docs/reports/field-coverage.md so CI can diff it over time.

import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';

const root = process.cwd();
const schemaDirs = ['docs/standards/schemas/fmi2', 'docs/standards/schemas/fmi3'];
const sourceDirs = ['src/schema'];

function collectXsdNames(dir) {
  const names = new Map();
  for (const file of readdirSync(dir)) {
    if (!file.endsWith('.xsd')) continue;
    const text = readFileSync(join(dir, file), 'utf8');
    for (const match of text.matchAll(/<(?:xs:)?element[^>]*\bname="([^"]+)"/g)) {
      if (!names.has(match[1])) names.set(match[1], file);
    }
    for (const match of text.matchAll(/<(?:xs:)?attribute[^>]*\bname="([^"]+)"/g)) {
      if (!names.has(match[1])) names.set(match[1], file);
    }
  }
  return [...names.entries()]
    .map(([name, file]) => ({ name, file }))
    .sort((a, b) => (a.name < b.name ? -1 : 1));
}

// Names declared outside the runtime model description documents: the typed
// model in src/schema only parses modelDescription.xml, so these XSDs are
// out of scope for the coverage number (separate standard artifacts:
// build description, terminals & icons, layered manifests).
const outOfScopeFiles = new Set([
  'fmi3BuildDescription.xsd',
  'fmi3TerminalsAndIcons.xsd',
  'fmi3Terminal.xsd',
  'fmi3LayeredStandardManifest.xsd',
]);

function splitScope(entries) {
  const inScope = entries.filter((e) => !outOfScopeFiles.has(e.file));
  const outOfScope = entries.filter((e) => outOfScopeFiles.has(e.file));
  return { inScope, outOfScope };
}

function collectSourceText() {
  let text = '';
  for (const dir of sourceDirs) {
    for (const file of readdirSync(dir)) {
      if (file.endsWith('.mbt')) {
        text += readFileSync(join(dir, file), 'utf8');
      }
    }
  }
  return text;
}

function camelCase(name) {
  // xs:attribute names are lowerCamelCase already; keep the raw form and a
  // snake_case variant for tolerant matching.
  return [name, name.replace(/([A-Z])/g, '_$1').toLowerCase()];
}

const xsd2 = collectXsdNames(join(root, schemaDirs[0]));
const xsd3 = collectXsdNames(join(root, schemaDirs[1]));
const sources = collectSourceText();

function coverage(names) {
  const covered = [];
  const missing = [];
  for (const name of names) {
    const found = camelCase(name).some((variant) => sources.includes(`"${variant}"`));
    (found ? covered : missing).push(name);
  }
  return { covered, missing };
}

const report2 = coverage(xsd2.map((e) => e.name));
const report3 = coverage(xsd3.map((e) => e.name));
const scope3 = splitScope(xsd3);
const scope3InReport = coverage(scope3.inScope.map((e) => e.name));

let markdown = '# XSD field coverage (B-19)\n\n';
markdown += '> Generated by `node tools/field-coverage.mjs`. A name is "covered" when the\n';
markdown += '> schema parser or model in `src/schema` mentions it as a string literal —\n';
markdown += '> i.e. the typed model carries the field or the parser rejects it explicitly.\n\n';
markdown += '> Scope note (2026-11-18): the headline numbers only count names from the\n';
markdown += '> runtime model-description XSDs. Names from fmi3BuildDescription.xsd,\n';
markdown += '> fmi3TerminalsAndIcons.xsd, fmi3Terminal.xsd and\n';
markdown += '> fmi3LayeredStandardManifest.xsd are separate artifacts the parser never\n';
markdown += '> consumes; they are listed at the end instead of being counted as gaps.\n\n';
const fmi2Rows = [["FMI 2", xsd2.length, report2]];
for (const [label, total, report] of fmi2Rows) {
  markdown += '## ' + label + '\n\n';
  markdown += '- declared in XSD: ' + total + '\n';
  markdown += '- covered by the typed model: ' + report.covered.length + ' (' + Math.round((100 * report.covered.length) / total) + '%)\n';
  markdown += '- not covered: ' + report.missing.length + '\n\n';
  if (report.missing.length > 0) {
    markdown += 'Missing names (candidates for future P1-style rule work):\n\n';
    for (const name of report.missing) {
      markdown += '- `' + name + '`\n';
    }
    markdown += '\n';
  }
}
{
  const total = scope3.inScope.length;
  const report = scope3InReport;
  markdown += '## FMI 3 (model-description scope)\n\n';
  markdown += '- declared in model-description XSDs: ' + total + '\n';
  markdown += '- covered by the typed model: ' + report.covered.length + ' (' + Math.round((100 * report.covered.length) / total) + '%)\n';
  markdown += '- not covered: ' + report.missing.length + '\n\n';
  if (report.missing.length > 0) {
    markdown += 'Missing names:\n\n';
    for (const name of report.missing) {
      markdown += '- `' + name + '`\n';
    }
    markdown += '\n';
  }
  const allTotal = xsd3.length;
  markdown += '- all-FMI-3-XSD coverage (previous headline): ' + report3.covered.length + '/' + allTotal + ' (' + Math.round((100 * report3.covered.length) / allTotal) + '%)\n\n';
}
{
  const byFile = new Map();
  for (const entry of scope3.outOfScope) {
    if (!byFile.has(entry.file)) byFile.set(entry.file, []);
    byFile.get(entry.file).push(entry.name);
  }
  markdown += '## FMI 3 out-of-scope names (separate standard artifacts)\n\n';
  for (const [file, names] of [...byFile.entries()].sort()) {
    markdown += '- ' + file + ': ' + names.length + ' names\n';
  }
  markdown += '\n';
}
markdown += '\n> 注:`missing` 不是缺陷清单——部分 XSD 名称(枚举值、类型名)由语义层处理,\n';
markdown += '> 判定规则是字符串字面量匹配,因此存在少量误报。数字只用于跟踪趋势。\n';

mkdirSync(join(root, 'docs/reports'), { recursive: true });
writeFileSync(join(root, 'docs/reports/field-coverage.md'), markdown);
console.log('FMI 2: ' + report2.covered.length + '/' + xsd2.length + ' covered');
console.log('FMI 3 (model-description scope): ' + scope3InReport.covered.length + '/' + scope3.inScope.length + ' covered');
console.log('report written to docs/reports/field-coverage.md');
